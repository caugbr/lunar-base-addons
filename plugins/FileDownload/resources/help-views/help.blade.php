    <header>
        <h3><x-lucide-file-down class="lucid-icon" /> Arquivo para Download</h3>
        <p>Disponibiliza um card moderno e intuitivo para download de documentos (PDF, planilhas, arquivos ZIP, etc.).</p>
    </header>

    <h4>Como usar no Editor</h4>
    <p>No editor de blocos, abra o menu de blocos e escolha <strong>Arquivo para Download</strong>.</p>
    <ul>
        <li>Clique no espaço do card para abrir o gerenciador de mídias e selecionar o arquivo desejado.</li>
        <li>O nome do arquivo e a extensão serão identificados automaticamente, mas você pode editar o título diretamente clicando sobre ele.</li>
        <li>Você também pode personalizar o texto do botão de ação (ex: <em>"Baixar PDF"</em>, <em>"Ver Apostila"</em>).</li>
    </ul>
</div>
