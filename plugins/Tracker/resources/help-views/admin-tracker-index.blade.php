            Dashboard de Tráfego e Estatísticas
        </h3>
        <p>Visão geral de desempenho, engajamento e métricas de audiência do site em tempo real.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Privacidade e LGPD:</strong>
                O Tracker funciona de forma 100% nativa e sem cookies. Os IPs dos visitantes são convertidos em um hash criptográfico diário, garantindo a medição precisa sem rastrear dados pessoais.
            </li>
            <li>
                <strong>Visualizações Totais vs. Visitantes Únicos:</strong>
                <em>Visualizações</em> representam o total bruto de páginas carregadas. <em>Visitantes Únicos</em> indicam quantas pessoas ou dispositivos distintos navegaram pelo site no período.
            </li>
            <li>
                <strong>Picos de Acesso por Horário:</strong>
                O gráfico de horários compila o comportamento histórico (00h às 23h). Use esse indicador para agendar publicações e disparos em momentos de maior engajamento.
            </li>
            <li>
                <strong>Páginas Mais Visitadas e Origens:</strong>
                Acompanhe o ranking das URLs com mais audiência e identifique as fontes de tráfego externas (motores de busca, redes sociais ou acessos diretos).
            </li>
            <li>
                <strong>Eventos & Conversões:</strong>
                Mostra o volume de cliques em botões ou elementos com atributos de rastreamento configurados (ex: botão do WhatsApp, downloads de arquivos ou banners).
            </li>
        </ul>
    </div>

