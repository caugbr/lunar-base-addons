    <div class="help-header">
        <h3>
            <x-lucide-globe class="lucid-icon" />
            Origens de Tráfego (Referrers)
        </h3>
        <p>Descubra os domínios externos, redes sociais e buscadores que estão direcionando visitantes para o seu site.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>O que é um Referrer:</strong>
                É o endereço do site externo de onde o usuário clicou para chegar até você (ex: <code>google.com</code>, <code>instagram.com</code>, <code>facebook.com</code> ou outros portais parceiros).
            </li>
            <li>
                <strong>Acessos Diretos:</strong>
                Visitas em que o usuário digitou o endereço diretamente na barra do navegador, abriu um favorito salvo ou clicou em links em apps com proteção estrita de privacidade não geram referrer e não são listadas aqui.
            </li>
            <li>
                <strong>Filtros de Pesquisa:</strong>
                Você pode filtrar por um domínio específico para saber o impacto de uma parceria, campanha ou rede social em particular.
            </li>
            <li>
                <strong>Link Externo:</strong>
                O botão na coluna da direita permite abrir o domínio de origem correspondente para conferir de onde o tráfego está vindo.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                O Tracker remove automaticamente o prefixo <code>www.</code> para consolidar estatísticas vindas do mesmo domínio em uma única linha.
            </div>
        </div>
    </div>
