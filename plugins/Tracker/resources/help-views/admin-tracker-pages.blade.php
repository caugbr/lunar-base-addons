    <div class="help-header">
        <h3>
            <x-lucide-file-text class="lucid-icon" />
            Páginas Mais Visitadas
        </h3>
        <p>Relatório completo de visualizações por URL para entender quais conteúdos e seções atraem mais a atenção do público.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Caminho da Página (URL):</strong>
                Representa a rota acessada pelo visitante relativa à raiz do site (por exemplo, <code>/</code> para a home, <code>/contato</code> ou <code>/blog/post-exemplo</code>).
            </li>
            <li>
                <strong>Visualizações Totais vs. Visitantes Únicos:</strong>
                <em>Visualizações Totais</em> contabiliza toda vez que a página foi carregada, enquanto <em>Visitantes Únicos</em> mede quantos acessos distintos ocorreram naquela URL específica (desconsiderando múltiplos reloads do mesmo usuário no mesmo dia).
            </li>
            <li>
                <strong>Buscar por URL:</strong>
                Utilize o campo de busca para filtrar páginas específicas, diretórios de conteúdo (ex: <code>cursos/</code> ou <code>artigos/</code>) ou consultar a performance de uma página recém-lançada.
            </li>
            <li>
                <strong>Atalho para Página:</strong>
                O botão de link externo na coluna de ações permite abrir diretamente a página no site em uma nova aba do navegador.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                URLs com parâmetros de query string (ex: <code>?utm_source=...</code>) têm seu caminho canônico unificado na barra de navegação para evitar fragmentação de métricas.
            </div>
        </div>
