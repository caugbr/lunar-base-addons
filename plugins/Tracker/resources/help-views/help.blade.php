            Tracker (Estatísticas de Acesso)
        </h3>
        <p>
            Monitoramento de tráfego, visualizações de páginas e métricas de audiência em tempo real, 100% nativo e focado em privacidade (sem cookies e em conformidade com a LGPD).
        </p>
    </header>

    <h4>Como o Tracker funciona</h4>
    <p>
        O plugin registra automaticamente as visitas em todas as páginas públicas do site. Ele descarta bots conhecidos e requisições da área administrativa para manter os dados limpos e precisos.
    </p>

    <h4>Privacidade e LGPD</h4>
    <ul>
        <li><strong>Sem Cookies:</strong> Não utiliza cookies de rastreamento no navegador do usuário (dispensa banners intrusivos).</li>
        <li><strong>Anonimização:</strong> O endereço IP do visitante é transformado em um hash criptográfico diário, permitindo calcular "Visitantes Únicos" sem armazenar nenhum dado pessoal ou identificável.</li>
        <li><strong>Dados Locais:</strong> Todas as estatísticas permanecem exclusivamente no seu próprio banco de dados, sem compartilhamento com empresas terceiras (como Google, Meta, etc.).</li>
    </ul>

    <h4>Métricas Disponíveis</h4>
    <ul>
        <li><strong>Visualizações Totais (Pageviews):</strong> Número total de páginas carregadas no período.</li>
        <li><strong>Visitantes Únicos:</strong> Estimativa de pessoas distintas que acessaram o site.</li>
        <li><strong>Visualizações Diárias:</strong> Gráfico com a evolução do tráfego nos últimos 30 dias.</li>
        <li><strong>Páginas Mais Visitadas:</strong> Ranking das URLs mais acessadas pelos usuários.</li>
        <li><strong>Origens de Tráfego:</strong> Sites e redes sociais de onde os visitantes vieram (Google, Instagram, Facebook, etc.).</li>
        <li><strong>Dispositivos:</strong> Proporção de acessos via Computador (Desktop), Celular (Mobile) ou Tablet.</li>
    </ul>

    <h4>Acessando o Painel</h4>
    <p>
        Para visualizar os relatórios e gráficos, acesse no menu administrativo:
        <strong>Admin → Tracker</strong> (ou através da rota <code>/admin/tracker</code>).
    </p>
