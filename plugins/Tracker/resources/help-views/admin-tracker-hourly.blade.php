        <h3>
            <x-lucide-clock class="lucid-icon" />
            Picos de Visitação por Horário
        </h3>
        <p>Análise da distribuição horária dos acessos ao longo do dia para identificar os momentos de maior engajamento.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Como funciona o cálculo:</strong>
                O relatório agrupa todas as visualizações ocorridas no período selecionado dentro das 24 faixas de horas do dia (das 00h às 23h), somando o total acumulado em cada hora.
            </li>
            <li>
                <strong>Horário de Pico:</strong>
                O card de destaque e a linha destacada na tabela indicam o intervalo exato que mais recebeu visitas. Esse dado é valioso para planejar publicações de notícias, posts em redes sociais e disparos de e-mail marketing.
            </li>
            <li>
                <strong>Filtro de Período:</strong>
                Altere a quantidade de dias no filtro para observar tendências sazonais (por exemplo, os últimos 7 dias para um panorama recente ou 90 dias para um padrão consolidado).
            </li>
            <li>
                <strong>Fuso Horário:</strong>
                Os dados utilizam o fuso horário configurado no servidor/aplicação (configuração padrão do sistema).
            </li>
        </ul>
    </div>

