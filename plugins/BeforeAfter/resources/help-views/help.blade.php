        <h3><x-lucide-columns class="lucid-icon" /> Before / After (Comparador)</h3>
        <p>Adiciona um bloco interativo para comparar duas imagens (Antes e Depois) utilizando um controle deslizante (slider).</p>
    </header>

    <h4>Como usar no Editor</h4>
    <p>No editor de blocos, abra o menu de inserção e selecione <strong>Before / After</strong>. O bloco exibirá dois espaços dedicados para as imagens.</p>
    <ul>
        <li>Clique em <strong>Selecionar "Antes"</strong> para escolher ou enviar a primeira imagem através do gerenciador de mídias.</li>
        <li>Clique em <strong>Selecionar "Depois"</strong> para escolher a segunda imagem.</li>
        <li>O layout no editor é diferente. Para testar o comportamento em tempo real, veja a página no frontend.</li>
    </ul>
