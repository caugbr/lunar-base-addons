    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Como os dados são coletados:</strong>
                O rastreador opera de forma silenciosa e em segundo plano para visitantes deslogados. Sempre que alguém clica, pausa a leitura ou rola uma página, os dados são acumulados e processados pelo sistema.
            </li>
            <li>
                <strong>Filtro de período:</strong>
                Utilize o seletor no canto superior direito para alternar a exibição entre os últimos 7, 30 ou 90 dias, permitindo comparar o engajamento recente com dados históricos.
            </li>
            <li>
                <strong>Abrir página pública:</strong>
                O primeiro botão de ação abre a URL correspondente em uma nova aba do navegador para que você possa conferir o conteúdo original publicado.
            </li>
            <li>
                <strong>Visualizar mapa:</strong>
                O botão de olho abre o visualizador gráfico completo, onde você pode analisar os mapas de cliques, pausas de atenção e profundidade de rolagem sobrepostos ao layout.
            </li>
            <li>
                <strong>Limpeza de métricas:</strong>
                O botão de lixeira permite zerar o histórico de interações apenas daquela URL específica. Isso é ideal para reiniciar a contagem após publicar um novo design ou uma reformulação de conteúdo.
            </li>
        </ul>
    </div>

