<div class="plugin-help-content">
    <header>
        <h3>
            <x-lucide-qr-code class="lucid-icon" /> Gerador de QR Code
        </h3>
        <p>
            Crie QR Codes dinâmicos em vetor (SVG) para compartilhar links de artigos, páginas ou conteúdos livres para materiais impressos e digitais.
        </p>
    </header>

    <h4>Integrações Automáticas por Hooks</h4>
    <p>O plugin conecta-se automaticamente em locais estratégicos do painel administrativo:</p>

    <ul>
        <li><strong>Tabelas de Posts e Páginas:</strong> Ícone discreto de QR Code na coluna de ações rápidas.</li>
        <li><strong>Header de Edição:</strong> Botão dedicado de visualização rápida no topo do formulário de edição de artigos e páginas.</li>
    </ul>

    <h4>Uso Livre no Painel</h4>
    <p>
        Acesse <strong>Ferramentas → Gerador QR Code</strong> para criar imagens personalizadas com qualquer texto, link, dados de PIX ou redes sociais com download direto em alta resolução (SVG).
    </p>

    <blockquote>
        <strong>Dica de Desempenho:</strong>
        <p>
            A renderização utiliza o mecanismo vetorial nativo em SVG. Isso garante que a imagem não perca resolução ao ser ampliada para impressão e não sobrecarregue o banco de dados.
        </p>
    </blockquote>
</div>
