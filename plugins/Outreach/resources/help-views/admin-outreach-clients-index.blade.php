    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Gestão de Contatos (Leads)
        </h3>
        <p>Centralize seus potenciais clientes, filtre por etapas comerciais e inicie abordagens por e-mail.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Filtros e Busca Textual:</strong>
                Pesquise rapidamente digitando o nome do contato, e-mail, empresa ou cargo. O seletor de status permite restringir a lista ao funil desejado.
            </li>
            <li>
                <strong>Abas de Status com Contadores:</strong>
                As pílulas no topo exibem a quantidade exata de contatos em cada etapa (Novos, Contatados, Em Conversa, Fechados e Descartados). Quando uma busca é feita, os contadores recalculam com base no termo pesquisado.
            </li>
            <li>
                <strong>Disparo em Lote:</strong>
                Marque os checkboxes dos contatos desejados (ou selecione todos na primeira coluna), escolha o modelo de e-mail na barra superior direita e clique em <strong>Disparar</strong> para avançar à tela de revisão.
            </li>
            <li>
                <strong>Linha do Tempo e Anotações:</strong>
                A coluna com o ícone de mensagem indica quantas anotações existem para aquele cliente. Clique no ícone de visualização (<x-lucide-eye class="lucid-icon" style="width: 14px; height: 14px;" />) para abrir o perfil completo e a timeline.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                Para cadastrar um lead avulso, clique no botão <strong>Novo Contato</strong> no cabeçalho da página.
            </div>
        </div>
